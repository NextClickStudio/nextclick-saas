/**
 * The trend catalogue: every card points to one of these trends.
 * Used by `npm run seed:sql` only (the app reads trends from the database).
 *
 * Rules: generic names only. No brand names, no signature designs of a brand.
 * `q` is what we search on Google Trends: specific enough to mean fashion
 * ("sage green dress", not "sage").
 */
import type { Family } from "../lib/cards/families";
import type { MaterialSpec } from "../lib/cards/materials";

export interface Trend {
  id: string;
  name: string;
  family: Family;
  query: string;
  /** Colour cards: the colour itself. */
  hex?: string;
  /** Fabric cards: texture + its colours. */
  material?: MaterialSpec & { main: string; accent: string };
  /** Aesthetic cards: two mood colours. */
  mood?: [string, string];
}

type M = Trend["material"];
const t = (family: Family) => (id: string, name: string, query = name.toLowerCase()): Trend => ({ id, name, family, query });
const piece = t("piece");
const shoes = t("shoes");
const acc = t("accessory");
const detail = t("detail");
const beauty = t("beauty");
const color = (id: string, name: string, hex: string, query = `${name.toLowerCase()} dress`): Trend => ({ id, name, family: "color", query, hex });
const fabric = (id: string, name: string, query: string, material: M): Trend => ({ id, name, family: "material", query, material });
const mood = (id: string, name: string, m: [string, string], query = `${name.toLowerCase()} aesthetic`): Trend => ({ id, name, family: "aesthetic", query, mood: m });

